import asyncio, json, subprocess, time, sys, datetime as dt
from playwright.async_api import async_playwright
PORT=8765
srv = subprocess.Popen([sys.executable,'-m','http.server',str(PORT),'--bind','127.0.0.1'], cwd='/home/claude/outperf-gh', stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(0.8)
URL=f'http://localhost:{PORT}/'
SH='/home/claude/outperf-gh/app/test/shots/'
errors=[]
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width':390,'height':844}, device_scale_factor=2, is_mobile=True, has_touch=True, color_scheme='dark', locale='fr-FR', timezone_id='Europe/Paris')
        page = await ctx.new_page()
        page.on('console', lambda m: errors.append(('console',m.type,m.text)) if m.type in ('error','warning') else None)
        page.on('pageerror', lambda e: errors.append(('pageerror',str(e))))
        await page.clock.install(time=dt.datetime(2026,10,6,9,0,0))
        await page.goto(URL)
        await page.wait_for_timeout(400)
        await page.screenshot(path=SH+'01_onboarding.png')
        await page.get_by_role('button', name='Commencer').click(); await page.get_by_role('button', name='Continuer').click()
        await page.wait_for_timeout(300)
        await page.screenshot(path=SH+'02_today_empty.png', full_page=True)
        # quick add +1 h to first category
        await page.get_by_role('button', name='Ajouter du temps à Révision cours').nth(1).click()
        await page.wait_for_timeout(350)
        await page.screenshot(path=SH+'03_quickadd.png')
        await page.get_by_role('button', name='+1 h', exact=True).click()
        await page.wait_for_timeout(300)
        n = await page.evaluate('window.__op.S.entries.length')
        print('entries after quick add', n)
        # start chrono for Travail projets
        await page.get_by_role('button', name='Lancer le chrono pour Travail projets').click()
        await page.clock.fast_forward('42:13')
        await page.wait_for_timeout(1200)
        await page.screenshot(path=SH+'04_chrono_running.png')
        # go to today: live
        await page.locator('#tabs .tab').nth(0).click()
        await page.wait_for_timeout(1200)
        await page.screenshot(path=SH+'05_today_live.png', full_page=True)
        m = await page.evaluate('window.__op.metrics()')
        print('today live min', round(m['today'],2))
        # finish chrono
        await page.locator('#tabs .tab').nth(1).click()
        await page.get_by_role('button', name='Terminer').click()
        await page.wait_for_timeout(300)
        ents = await page.evaluate('window.__op.S.entries.map(e=>[e.c,e.m,e.src,e.d])')
        print('entries', ents)
        # minuteur 25 min, round completes while "away"
        await page.get_by_role('tab', name='Minuteur').click()
        await page.get_by_role('button', name='25 min', exact=True).click()
        await page.get_by_role('button', name='Lancer un round de 25 min').click()
        await page.clock.fast_forward('26:00')
        await page.wait_for_timeout(1500)
        await page.screenshot(path=SH+'06_round_done.png')
        ents = await page.evaluate('window.__op.S.entries.map(e=>[e.m,e.src])')
        print('after round', ents)
        await page.get_by_role('button', name='Pause de 5 min').click()
        await page.wait_for_timeout(500)
        await page.screenshot(path=SH+'07_break.png')
        await page.get_by_role('button', name='Passer la pause').click()
        # midnight split test
        split = await page.evaluate('''() => { const a=new Date(2026,9,6,23,30).getTime(), b=new Date(2026,9,7,0,45).getTime(); return [...window.__op.splitSegs([[a,b]])].map(([k,v])=>[k,v/60000]); }''')
        print('split', split)
        # parsing
        tests = ['2h30','1h','45 min','1,5','1:30','3 h 15','90min','2.25','',  '-']
        print('dur', await page.evaluate('(t)=>t.map(x=>window.__op.parseDuration(x))', tests))
        print('date', await page.evaluate('(t)=>t.map(x=>window.__op.parseDate(x, 2026))', ['05/10','05/10/2026','2026-09-30','lun 06/10','12/12','5 oct','31/02']))
        tbl = "Date\tRévision\tProjets\tSport\tTotal\n01/10\t2h30\t1h\t45min\t4h15\n02/10\t3h\t1,5\t\t4,5\n03/10\t\t2h\t1h\t"
        print('table', json.dumps(await page.evaluate('(t)=>window.__op.parseTable(t)', tbl), ensure_ascii=False)[:400])
        print('lines', json.dumps(await page.evaluate('(t)=>window.__op.parseTable(t)', "Lun 29/09 : 4h30\nMar 30/09 : 5h\n01/10 - 3h45\n"), ensure_ascii=False)[:300])
        # demo + stats
        await page.evaluate('window.__op.loadDemo()')
        await page.wait_for_timeout(300)
        await page.locator('#tabs .tab').nth(0).click()
        await page.wait_for_timeout(300)
        await page.screenshot(path=SH+'08_today_demo.png', full_page=True)
        await page.locator('#tabs .tab').nth(2).click()
        await page.wait_for_timeout(600)
        await page.screenshot(path=SH+'09_stats.png', full_page=True)
        # tooltip on a 30-day bar
        hits = page.locator('.chart .hit')
        await hits.nth(25).click()
        await page.wait_for_timeout(200)
        await page.screenshot(path=SH+'10_tooltip.png')
        await page.locator('#tabs .tab').nth(3).click()
        await page.wait_for_timeout(300)
        await page.locator('.day-h').first.click()
        await page.wait_for_timeout(200)
        await page.screenshot(path=SH+'11_journal.png', full_page=True)
        await page.locator('#tabs .tab').nth(4).click()
        await page.wait_for_timeout(300)
        await page.screenshot(path=SH+'12_settings.png', full_page=True)
        await page.locator('.row-main').first.click()
        await page.wait_for_timeout(350)
        await page.screenshot(path=SH+'13_editcat.png')
        await page.keyboard.press('Escape')
        # light theme
        await page.get_by_role('button', name='Clair', exact=True).click()
        await page.locator('#tabs .tab').nth(2).click()
        await page.wait_for_timeout(600)
        await page.screenshot(path=SH+'14_stats_light.png', full_page=True)
        await page.locator('#tabs .tab').nth(0).click()
        await page.wait_for_timeout(300)
        await page.screenshot(path=SH+'15_today_light.png', full_page=True)
        # persistence after reload
        cnt = await page.evaluate('window.__op.S.entries.length')
        await page.reload(); await page.wait_for_timeout(500)
        cnt2 = await page.evaluate('window.__op.S.entries.length')
        print('persist', cnt, cnt2)
        sw = await page.evaluate('navigator.serviceWorker.getRegistration().then(r=>!!r)')
        print('sw registered', sw)
        await b.close()
asyncio.run(main())
srv.terminate()
print('ERRORS', errors)
